package org.dromara.djs.warehouse.demand.controller;

import org.dromara.djs.warehouse.demand.domain.vo.DemandPrintSummaryVo;
import org.dromara.djs.warehouse.demand.service.IDemandPrintService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;

import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.ArgumentMatchers.isNull;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** Exercise Spring MVC parameter binding, including the actual indexed query generated by the admin HTTP client. */
@Tag("local")
@Tag("dev")
@DisplayName("需求汇总打印请求参数绑定")
class DemandPrintControllerBindingTest {
    private static final LocalDate DAY = LocalDate.of(2026, 11, 10);
    private static final long FIRST_STORE = 9311109690000014L;
    private static final long SECOND_STORE = 9311109690000016L;
    private IDemandPrintService service;
    private MockMvc mvc;

    @BeforeEach
    void setup() {
        service = mock(IDemandPrintService.class);
        // Only binding is isolated here; permission annotation and full-stack permission checks remain separate tests.
        mvc = MockMvcBuilders.standaloneSetup(new DemandPrintController(service)).build();
    }

    static Stream<Arguments> storeFilters() {
        return Stream.of(
            Arguments.of(Map.of("storeIds[0]", List.of(String.valueOf(SECOND_STORE))), List.of(SECOND_STORE)),
            Arguments.of(Map.of("storeIds[0]", List.of(String.valueOf(FIRST_STORE)),
                "storeIds[1]", List.of(String.valueOf(SECOND_STORE))), List.of(FIRST_STORE, SECOND_STORE)),
            Arguments.of(Map.of("storeIds", List.of(String.valueOf(FIRST_STORE), String.valueOf(SECOND_STORE))),
                List.of(FIRST_STORE, SECOND_STORE)),
            Arguments.of(Map.of("storeIds", List.of(FIRST_STORE + "," + SECOND_STORE)),
                List.of(FIRST_STORE, SECOND_STORE))
        );
    }

    @ParameterizedTest
    @MethodSource("storeFilters")
    @DisplayName("indexed、repeated、CSV形式都将精确日期与门店传给service")
    void summaryBindsStoreFilters(Map<String, List<String>> parameters, List<Long> expectedStores) throws Exception {
        DemandPrintSummaryVo result = emptySummary();
        when(service.getSummary(eq(DAY), eq(expectedStores))).thenReturn(result);
        MockHttpServletRequestBuilder request = get("/djs/warehouse/demand/print/summary")
            .param("demandDate", "2026-11-10");
        parameters.forEach((key, values) -> request.param(key, values.toArray(String[]::new)));

        mvc.perform(request)
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.code").value(200))
            .andExpect(jsonPath("$.data.items").isEmpty());

        verify(service).getSummary(DAY, expectedStores);
    }

    @Test
    @DisplayName("不选门店才明确传null表示全部门店")
    void summaryWithoutStoreFilterPassesNull() throws Exception {
        when(service.getSummary(eq(DAY), isNull())).thenReturn(emptySummary());
        mvc.perform(get("/djs/warehouse/demand/print/summary").param("demandDate", "2026-11-10"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.code").value(200));
        verify(service).getSummary(DAY, null);
    }

    private static DemandPrintSummaryVo emptySummary() {
        DemandPrintSummaryVo result = new DemandPrintSummaryVo();
        result.setDemandDate(DAY);
        result.setItems(List.of());
        return result;
    }
}
