-- ============================================================
-- FIX-BRD-AD-MENU-CLEANUP-001  隐藏后台养殖侧 6 个不需要的菜单项（K163）
-- ============================================================
-- 客户反馈：后台养殖侧边栏存在多个当前业务不需要的功能菜单，需去掉。
-- 明列 6 个父菜单 + 其下挂的 F 型按钮：
--   7070 药品批次 / 7076 药品领用 / 7085 用药治疗 / 7400 养殖看板 / 7110 仔猪耳标 / 7140 生长记录
-- 药品库父菜单 7060 默认**保留**（G3），仅隐藏明列 6 项。
--
-- 处理：父菜单 visible='1'（隐藏出 admin 侧边栏）；其子按钮 parent_id 命中同样置 '1' 保持一致。
-- 安全性：visible 只控 admin 侧边栏渲染；role_menu 绑定 / sa-token 权限校验不动，仅做隐藏（可逆）。
-- 影响范围：admin 侧边栏少 6 个分组项；用户重新登录后刷新生效。
-- ============================================================

UPDATE sys_menu SET visible = '1'
WHERE menu_id IN (7070, 7076, 7085, 7400, 7110, 7140)
   OR parent_id IN (7070, 7076, 7085, 7400, 7110, 7140);
