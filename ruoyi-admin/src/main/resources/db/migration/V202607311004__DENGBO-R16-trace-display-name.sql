-- DENGBO-R16 追溯码表加「定格展示名」列
--
-- 果蔬产品按「原材料对应作物是否有有效有机证书」决定展示名（有证=产品名 / 无证=别名）。
-- 追溯码生成时定格该刻展示名进本列（快照语义：证书事后过期 / 产品事后改名，
-- 历史追溯码显示不变）；显示层优先读本列，NULL 时兜底 JOIN product 当前名（兼容旧码）。
-- ============================================================

ALTER TABLE t_warehouse_trace_code
    ADD COLUMN trace_display_name VARCHAR(128) NULL COMMENT '生码时定格的展示名(有证=产品名/无证=别名)' AFTER product_id;
