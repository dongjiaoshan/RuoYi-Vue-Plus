-- ============================================================================
-- V6 需求和问题（测试环境）row107：班组绩效计算加入「绩效百分比」
--
-- 甲方口径：
--   1. 绩效 = 采摘重量 × 绩效百分比 × 绩效单价；
--   2. 绩效详情「采摘量」右边加一列「绩效百分比」，同一产品的不同百分比拆成多条记录展示。
--
-- 落库：结算行按 班组 × 作物 × 产品 × 绩效百分比 分组，故本列进主键之外的分组维度。
-- 存量结算行由 DEFAULT 100 自动补齐 —— 历史月重算前后金额不变。
-- ============================================================================

SET NAMES utf8mb4;

ALTER TABLE t_plant_work_performance
    ADD COLUMN perf_percent INT NOT NULL DEFAULT 100
        COMMENT '绩效百分比(0-100 整数，%)：该行采摘量对应的绩效比例，金额 = 采摘量 × 百分比 × 单价快照'
        AFTER product_id;
