-- V6 需求和问题（测试环境）row105：毛菜处理 · 采摘重量录入弹窗新增「绩效百分比」
--
-- 甲方口径：
--   1. 采摘班组设为必填；
--   2. 采摘班组下面新增「绩效百分比」，必填、单位 %、整数、最多 100、默认 100，可改；
--   3. 绩效百分比下面新增「备注」，非必填；
--   4. 新增字段与称重记录保存在一起。
--
-- 落库：
--   perf_percent → t_warehouse_handle_record（与称重流水同表，满足第 4 条）；
--   备注复用该表已有的 remark VARCHAR(500) 列，不新建列。
--
-- 存量行由 DEFAULT 100 自动补齐 —— 改造前录的采摘全额计绩效，与既有结算金额一致。
-- ============================================================================

SET NAMES utf8mb4;

ALTER TABLE t_warehouse_handle_record
    ADD COLUMN perf_percent INT NOT NULL DEFAULT 100
        COMMENT '绩效百分比(0-100 整数，%)：本次采摘按此比例计入班组绩效，仅 record_type=1 采收行有业务含义'
        AFTER team_id;
