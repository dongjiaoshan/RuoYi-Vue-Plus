-- ============================================================
-- FIX-WMS-MP-MENU-HIDE-001  隐藏仓库 mp 占位 M 菜单（admin 点击 404 修复）
-- ============================================================
-- 现象：admin 侧边栏点「仓库 > 生产管理 > 打包工序」→ /djs-warehouse/wh-production/# 404。
-- 根因：打包工序(9220) 等是 menu_type='M' 的 mp 工序占位父菜单——只挂 mp 的 F 型按钮权限
--       （如 9221-9224 djs:applet:warehouse:pack:*），**无 admin C 型子页**、自身 component 为空。
--       seed 时 visible='0'（显示），ADMIN-MENU-IA-001 又把它们挂进可见分组父下，于是在 admin
--       侧边栏渲染成可点项，点击解析到无组件的路由 → 404。
-- 修复：把这 4 个 mp-only 占位 M 菜单 visible 改 '1'（隐藏出 admin 侧边栏），对齐既有范式
--       （商品旧入口 9030 / 产品三入口 9036-9038「默认隐藏 visible='1'」）。
-- 安全性：visible 只控 admin 侧边栏渲染；mp 的 F 子权限 role_menu 绑定独立、sa-token 照常校验，
--         小程序导航走自身硬编码页面、不读 sys_menu，故隐藏父 M 不影响 mp。admin 对应只读页
--         另有专门 C 菜单（打包→生产记录 9230 / 盘点录入→库存盘点 9250），功能不丢。
-- 影响范围：仅 admin 侧边栏少 4 个死链项；用户重新登录后刷新。
-- ============================================================

UPDATE sys_menu SET visible = '1'
WHERE menu_id IN (
    9220,  -- 打包工序（mp 4 类打包占位；admin 看 生产记录 9230）
    9246,  -- 包材库（mp 包材库占位）
    9260,  -- 盘点录入（mp 盘点录入占位；admin 看 库存盘点 9250）
    9270   -- 需求调度（mp 调度员入口容器）
);
