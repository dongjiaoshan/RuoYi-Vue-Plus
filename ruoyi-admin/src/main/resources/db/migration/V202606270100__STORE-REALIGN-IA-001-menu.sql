-- ============================================================
-- STORE-REALIGN-IA-001  门店域菜单 IA 对齐原型 5 板块  纯 menu seed
-- ============================================================
-- 权威源：doc/origin/prototype/admin/_real_screenshots/origin_screenshots/门店管理/
--   左侧 5 板块 = 门店总览 / 需求管理 / 门店管理 / 追溯码管理 / 退回管理
-- 本迁移只动 sys_menu 的 menu_name / parent_id / order_num / visible（不删菜单、不改 perms/component）。
-- 各板块新增子页（产品管理 / 猪肉追溯码管理 / 退回操作）随各自板块迁移单独 seed，
--   以保证任一时刻菜单都指向已存在的可用页面。
-- 原型外模块（门店经营 10100 / 门店分割 10300）按 Kevin 2026-06-12 拍板隐藏（保留表作数据源）；
--   会员档案 10320 维持隐藏（FIX-STR-MEMBER-REMOVE-001，PC 端会员本就是 V2 OoS）。
-- 追溯 10500 由顶级菜单迁入门店域 10000 下，对齐原型「追溯码管理」板块归属。
-- ============================================================
SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 1. 门店总览：撤隐藏 + 改名（原型板块①，看板着陆页 order_num=0）
-- ------------------------------------------------------------
UPDATE sys_menu SET menu_name = '门店总览', visible = '0', order_num = 0
WHERE menu_id = 10400;

-- ------------------------------------------------------------
-- 2. 需求管理（原型板块②）：父 + 列表 改名
-- ------------------------------------------------------------
UPDATE sys_menu SET menu_name = '需求管理', order_num = 1 WHERE menu_id = 10001;
UPDATE sys_menu SET menu_name = '需求列表' WHERE menu_id = 10002;

-- ------------------------------------------------------------
-- 3. 门店管理（原型板块③）：分组父归位 order_num=2
--    （产品管理子页随 STORE-REALIGN-PRODUCT 迁移补 seed + 调门店盘点 order）
-- ------------------------------------------------------------
UPDATE sys_menu SET order_num = 2 WHERE menu_id = 10600;

-- ------------------------------------------------------------
-- 4. 追溯码管理（原型板块④）：追溯一级菜单迁入门店域 + 改名
--    10500「追溯」(parent 0) → parent 10000, 改名「追溯码管理」, order_num=3
--    10501「追溯码管理」→ 改名「果蔬追溯码管理」（猪肉现场生码子页随 TRC 迁移补 seed）
-- ------------------------------------------------------------
UPDATE sys_menu SET menu_name = '追溯码管理', parent_id = 10000, order_num = 3
WHERE menu_id = 10500;
UPDATE sys_menu SET menu_name = '果蔬追溯码管理', order_num = 1 WHERE menu_id = 10501;

-- ------------------------------------------------------------
-- 5. 退回管理（原型板块⑤）：分组父归位 + 现单页改名为「退回记录」
--    （退回操作子页随 STORE-RETURN-REALIGN 迁移补 seed）
-- ------------------------------------------------------------
UPDATE sys_menu SET order_num = 4 WHERE menu_id = 10601;
UPDATE sys_menu SET menu_name = '退回记录', order_num = 2 WHERE menu_id = 10350;

-- ------------------------------------------------------------
-- 6. 隐藏原型外模块（保留表/后端作 dashboard·盘点·mp 数据源，可逆）
--    门店经营 10100（产品关联 10110 / 经营明细 10120 随父隐藏）
--    门店分割 10300（孤岛 + 业务理由 P1 待澄清）
-- ------------------------------------------------------------
UPDATE sys_menu SET visible = '1' WHERE menu_id = 10100;
UPDATE sys_menu SET visible = '1' WHERE menu_id = 10300;
