-- ============================================================
-- SYS-FIX-006 重命名根部门 + 清 ruoyi 默认演示部门
--
-- 背景：
--   V202605201700 SYS-CLEANUP 注释明示 "sys_dept 留待 SYS-MD-001 业务人员管理
--   落地时 rename"。SYS-MD-001 已确定走 sys_user 路径（ADR-0007），
--   SYS-FIX-005 收尾后这里一并把根部门 rename + 清 ruoyi 演示部门。
--
-- 现状 sys_dept：
--   100 XXX科技
--   ├── 101 深圳总公司 → 103/104/105/106/107 研发/市场/测试/财务/运维部门
--   ├── 102 长沙分公司 → 108/109 市场/财务部门
--   └── 200/201/202/203/204 东角山-养殖部/种植部/仓库部/门店部/综合管理部 (D04 seed)
--
-- 改造：
--   1. admin (user_id=1) dept_id 103 → 100（避免删 103 后引用空悬）
--   2. 解 sys_role_dept 对 101-109 的引用（数据权限关联表，若有）
--   3. DELETE sys_dept WHERE dept_id BETWEEN 101 AND 109（清 ruoyi 演示部门）
--   4. UPDATE sys_dept SET dept_name='东角山智慧农场' WHERE dept_id=100 + 清假联系方式
-- ============================================================

SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 1. admin 用户的 dept_id 改挂顶层（103 研发部门即将被删）
-- ------------------------------------------------------------
UPDATE sys_user SET dept_id = 100 WHERE user_id = 1 AND dept_id = 103;

-- ------------------------------------------------------------
-- 2. 解 sys_role_dept 对 101-109 的引用（数据权限自定义部门关联）
-- ------------------------------------------------------------
DELETE FROM sys_role_dept WHERE dept_id BETWEEN 101 AND 109;

-- ------------------------------------------------------------
-- 3. 软删 ruoyi 演示部门 101-109（深圳总公司 / 长沙分公司 + 7 个子部门）
--    用 del_flag='2' 走 ruoyi 软删语义；同时把 status 也设停用，避免 UI 列表筛选误显示
-- ------------------------------------------------------------
UPDATE sys_dept
   SET del_flag = '2',
       status   = '1'
 WHERE dept_id BETWEEN 101 AND 109;

-- ------------------------------------------------------------
-- 4. 重命名根部门 100 → 东角山智慧农场 + 清假联系方式
-- ------------------------------------------------------------
UPDATE sys_dept
   SET dept_name = '东角山智慧农场',
       phone     = NULL,
       email     = NULL
 WHERE dept_id = 100;
